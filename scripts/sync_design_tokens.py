"""Regenerate Flutter palette/icon tokens from the reviewed design sources."""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
TARGET = ROOT / 'apps/vex/lib/ui/core'
TARGET.mkdir(parents=True, exist_ok=True)
palettes = json.loads(re.search(r'window.VexPalettes=(\[.*?\]);',
    (ROOT / 'design/assets/palettes.js').read_text(encoding='utf-8')).group(1))
css = (ROOT / 'design/assets/palettes.css').read_text(encoding='utf-8')
out = ['// Generated by scripts/sync_design_tokens.py; edit design/assets/palettes.*.',
       "import 'package:flutter/material.dart';", '',
       'const paletteNames = <String, String>{']
for p in palettes:
    out.append(f"  '{p['key']}': '{p['label']}',")
out += ['};', '', 'const paletteSchemes = <String, ColorScheme>{']
for theme in ['light', 'dark']:
    for p in palettes:
        block = re.search(r':root\[data-theme="' + theme + r'"\]\[data-palette="' + p['key'] + r'"\]\{([^}]+)', css).group(1)
        tokens = dict(re.findall(r'--([\w-]+):(#\w+)', block))
        mapping = dict(primary='accent', onPrimary='accent-fg', primaryContainer='accent-soft',
            onPrimaryContainer='accent', secondary='accent', onSecondary='accent-fg',
            error='accent', onError='accent-fg', surface='bg', onSurface='fg',
            onSurfaceVariant='muted', outline='muted', outlineVariant='border',
            surfaceContainerLow='panel', surfaceContainer='paper', surfaceContainerHigh='hover')
        out.append(f"  '{p['key']}-{theme}': ColorScheme(brightness: Brightness.{theme},")
        for key, token in mapping.items():
            value = tokens[token][1:]
            if key == 'error': value = 'DC2626' if theme == 'light' else 'FF828F'
            if key == 'onError': value = 'FFFFFF' if theme == 'light' else '281C24'
            out.append(f'    {key}: Color(0xff{value}),')
        out.append('  ),')
out += ['};', '']
(TARGET / 'palette_tokens.dart').write_text('\n'.join(out), encoding='utf-8')
html = (ROOT / 'design/Vex.html').read_text(encoding='utf-8')
icons = re.findall(r'<symbol id="i-([^\"]+)"[^>]*>(.*?)</symbol>', html, re.S)
out = ['// Generated by scripts/sync_design_tokens.py.', 'const appIconPaths = <String, String>{']
for name, data in icons:
    out.append('  ' + json.dumps(name) + ': ' + json.dumps(data.strip()) + ',')
out += ['};', '']
(TARGET / 'icon_paths.dart').write_text('\n'.join(out), encoding='utf-8')
print(f'Generated {len(palettes)} light/dark palettes and {len(icons)} icons.')
