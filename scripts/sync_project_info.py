"""Refresh prototype project metadata and primary dependency license notices.

Run after flutter pub get. The application uses PackageInfo and Flutter's
LicenseRegistry for its installed version and complete build notices.
"""
import html
import json
import pathlib
import re
import urllib.parse

ROOT = pathlib.Path(__file__).resolve().parents[1]
config_path = ROOT / '.dart_tool/package_config.json'
packages = json.loads(config_path.read_text(encoding='utf-8'))['packages']
roots = {}
for package in packages:
    uri = urllib.parse.urljoin(config_path.as_uri(), package['rootUri'])
    path = urllib.parse.unquote(urllib.parse.urlparse(uri).path)
    if re.match(r'^/[A-Za-z]:', path):
        path = path[1:]
    roots[package['name']] = pathlib.Path(path)

app_spec = (ROOT / 'apps/vex/pubspec.yaml').read_text(encoding='utf-8')
version = re.search(r'^version:\s*(\S+)', app_spec, re.M).group(1)
names = {'flutter', 'vex', 'vex_editor', 'vex_markdown_core', 'vex_mindmap'}
for relative in ['apps/vex', 'packages/vex_editor',
                 'packages/vex_markdown_core', 'packages/vex_mindmap']:
    spec = (ROOT / relative / 'pubspec.yaml').read_text(encoding='utf-8')
    block = re.search(r'^dependencies:\n(.*?)(?=^\S|\Z)', spec, re.M | re.S)
    if block:
        names.update(re.findall(r'^  ([a-z][a-z0-9_]*):', block.group(1), re.M))

notices = []
for name in sorted(names):
    source = roots[name]
    license_path = source / 'LICENSE'
    if name == 'vex':
        license_path = ROOT / 'LICENSE'
    if not license_path.exists() and name in {'flutter', 'flutter_localizations'}:
        license_path = source.parent.parent / 'LICENSE'
    if not license_path.exists():
        raise FileNotFoundError(f'Missing license for {name}: {license_path}')
    spec = (source / 'pubspec.yaml').read_text(encoding='utf-8')
    package_version = re.search(r'^version:\s*(\S+)', spec, re.M)
    notices.append((name, package_version.group(1) if package_version else 'SDK',
                    license_path.read_text(encoding='utf-8')))
dart_license = roots['flutter'].parent.parent / 'bin/cache/dart-sdk/LICENSE'
notices.append(('Dart', 'SDK', dart_license.read_text(encoding='utf-8')))
for name, file in [('Cascadia Code', 'CascadiaCode-OFL.txt'), ('Noto Sans SC', 'OFL.txt')]:
    notices.append((name, 'SIL Open Font License 1.1',
                    (ROOT / 'apps/vex/assets/fonts' / file).read_text(encoding='utf-8')))

info = {'version': version, 'copyright': 'Copyright © 2026 沙漠尽头的狼 / CodeWF',
        'repository': 'https://github.com/dotnet9/Vex-Flutter',
        'license': 'MIT', 'components': [name for name, _, _ in notices]}
(ROOT / 'design/assets/project-info.js').write_text(
    '// Generated by scripts/sync_project_info.py.\nwindow.VexProject = '
    + json.dumps(info, ensure_ascii=False) + ';\n'
    + 'if (window.VEX_DATA) Object.assign(VEX_DATA.metadata, '
    + '{version: VexProject.version, copyright: VexProject.copyright});\n'
    + "document.addEventListener('DOMContentLoaded', () => document.querySelectorAll('[data-project-components]').forEach(el => el.textContent = VexProject.components.join(' · ')));\n",
    encoding='utf-8')
items = '\n'.join('<details><summary>' + html.escape(name + ' · ' + ver)
                  + '</summary><pre>' + html.escape(text) + '</pre></details>'
                  for name, ver, text in notices)
page = '''<!doctype html><html lang="zh-CN"><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Vex · Open source licenses</title><style>
body{font:15px/1.8 system-ui,sans-serif;max-width:960px;margin:40px auto;padding:0 24px;color:#253835;background:#fafbf9}
a{color:#24766b}details{padding:12px 0;border-bottom:1px solid #dce4e1}summary{cursor:pointer;font-weight:600}pre{white-space:pre-wrap;overflow-wrap:anywhere;font:12px/1.8 ui-monospace,monospace}
</style><h1>Vex · 开源组件许可 / Open source licenses</h1>
<p>感谢下列实际使用的主要组件及字体。以下保留其原始许可声明。应用内“开源组件许可”提供该构建的完整依赖声明，包括间接依赖。</p>
<p>Primary components and fonts used by Vex. Original license notices are reproduced below.
The application's licenses page includes the complete notices for that build, including transitive dependencies.</p>
<p>繁體中文：感謝以下開源元件與字型。完整相依授權請見應用程式內的「開源元件授權」。<br>
日本語：使用している主なコンポーネントとフォントに感謝します。間接依存を含む全文はアプリのライセンス画面で確認できます。</p>
<p>Version: VERSION · <a href="https://github.com/dotnet9/Vex-Flutter">Source</a> · <a href="index.html">Design prototypes</a></p>
<p>桌面交互原型另使用 KaTeX 0.16.22（MIT）、mhchem（适配层 MIT，原始 MathJax/mhchem Apache-2.0）及 Mermaid 11.12.0（MIT）。<a href="assets/vendor/katex/LICENSE">KaTeX 许可</a> · <a href="assets/vendor/katex/mhchem-NOTICE">mhchem 声明</a> · <a href="assets/vendor/katex/Apache-2.0.txt">Apache-2.0 全文</a> · <a href="assets/vendor/mermaid/LICENSE">Mermaid 许可</a>。这些脚本仅用于原型演示。</p>
ITEMS</html>'''.replace('VERSION', html.escape(version)).replace('ITEMS', items)
(ROOT / 'design/Third-Party-Licenses.html').write_text(page, encoding='utf-8')
print(f'Project {version}: {len(notices)} primary component/font notices refreshed.')
