"""Synchronize presentation controls in the four supported application locales."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
keys = ('presentationOutline', 'presentationPrevious', 'presentationNext',
        'presentationSmaller', 'presentationLarger', 'presentationKeys', 'presentationMarkdown')
translations = {
    'zh': ('演示大纲', '上一页', '下一页', '减小演示字号', '增大演示字号',
           '← / →、PageUp / PageDown 翻页 · Home / End 首尾页 · Esc 退出', '正文'),
    'zh_Hant': ('簡報大綱', '上一頁', '下一頁', '縮小簡報字級', '放大簡報字級',
                '← / →、PageUp / PageDown 換頁 · Home / End 首末頁 · Esc 結束', '正文'),
    'en': ('Presentation outline', 'Previous slide', 'Next slide',
           'Decrease presentation text size', 'Increase presentation text size',
           '← / →, PageUp / PageDown: slides · Home / End: first / last · Esc: exit', 'Markdown'),
    'ja': ('プレゼンテーションのアウトライン', '前のスライド', '次のスライド',
           '文字を小さくする', '文字を大きくする',
           '← / →、PageUp / PageDown：移動 · Home / End：最初 / 最後 · Esc：終了', '本文'),
}
for locale, values in translations.items():
    path = root / f'apps/texweft/lib/l10n/app_{locale}.arb'
    data = json.loads(path.read_text(encoding='utf-8'))
    data.update(zip(keys, values))
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')

prototype = {
    {'zh': 'zh-CN', 'zh_Hant': 'zh-Hant', 'en': 'en-US', 'ja': 'ja-JP'}[locale]:
    dict(zip(keys, values)) for locale, values in translations.items()
}
for locale, target in {'zh': 'zh-CN', 'zh_Hant': 'zh-Hant', 'en': 'en-US', 'ja': 'ja-JP'}.items():
    data = json.loads((root / f'apps/texweft/lib/l10n/app_{locale}.arb').read_text(encoding='utf-8'))
    prototype[target]['exitPresentation'] = data['exitPresentation']
    prototype[target]['mindMap'] = data['mindMap']
(root / 'design/assets/presentation-labels.js').write_text(
    '// Generated by scripts/update_presentation_l10n.py.\n'
    + 'window.TexweftPresentationLabels = '
    + json.dumps(prototype, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
