const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const box = {window:{}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../assets/document-operations.js'),'utf8'),box);
const ops = box.window.VexDocumentOps;
const raw = '| 名称 | 内容 |\n| :--- | ---: |\n| A | `a|b` |\n| B | a\\|b |';
const value = ops.table(raw);
assert.equal(value.rows.length,3);
assert.equal(value.rows[1][1],'`a|b`');
assert.equal(value.rows[2][1],'a\\|b');
assert.equal(value.align[1],'right');
assert.equal(ops.table(ops.serialize(value)).rows[2][1],'a\\|b');
assert.equal(ops.changeTable(raw,'row-up',0,0),null);
assert.equal(ops.changeTable(raw,'row-up',1,0),null);
assert.equal(ops.changeTable(raw,'row-delete',0,0),null);
assert.equal(ops.changeTable(raw,'row-above',0,0),null);
assert.equal(ops.table(ops.changeTable(raw,'row-below',0,0).raw).rows.length,4);
assert.equal(ops.table(ops.changeTable(raw,'row-up',2,0).raw).rows[1][0],'B');
assert.equal(ops.changeTable(raw,'row-down',2,0),null);
assert.equal(ops.table(ops.changeTable(raw,'col-left',1,1).raw).align[0],'right');
assert.equal(ops.table(ops.changeTable(raw,'col-after',1,1).raw).align.length,3);
assert.equal(ops.table(ops.changeTable(raw,'align-center',1,1).raw).align[1],'center');
assert.equal(ops.table(ops.changeTable(raw,'row-delete',2,0).raw).rows.length,2);
assert.equal(ops.changeTable('| A |\n| --- |\n| B |','col-delete',1,0),null);
assert.equal(ops.table('not a table'),null);
assert.equal(ops.convert('## 标题','paragraph'),'标题');
assert.equal(ops.convert('标题\n===','heading3'),'### 标题');
assert.equal(ops.convert('- [x] 事项','ordered'),'1. 事项');
assert.equal(ops.convert('正文','quote'),'> 正文');
assert.equal(ops.wrap('abc',0,2,'**').text,'**ab**c');
assert.equal(ops.wrap('**ab**c',2,4,'**').text,'abc');
assert.equal(ops.wrap('abc',1,1,'**').text,'abc');
assert.equal(ops.inlineTokens('![图](assets/pic.png) [链接](https://example.com)')[1].kind,'link');
const cell=(text,align='')=>({text,dataset:{align},style:{}});
const dom={rows:[{cells:[cell('标题','center'),cell('内容','right')]},{cells:[cell('a|b'),cell('**粗体**')]}]};
const roundTrip=ops.table(ops.fromDOM(dom,cell=>cell.text));
assert.equal(roundTrip.align[0],'center');
assert.equal(roundTrip.align[1],'right');
assert.equal(roundTrip.rows[1][0],'a\\|b');
assert.equal(roundTrip.rows[1][1],'**粗体**');
const editorBox={window:box.window,Node:{TEXT_NODE:3,ELEMENT_NODE:1}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../assets/editor.js'),'utf8'),editorBox);
editorBox.VexDocumentOps=ops;
const parsed=editorBox.window.TexEditor.parse(raw);
assert.equal(parsed.blocks.length,1);
assert.equal(parsed.blocks[0].type,'table');
assert.ok(parsed.blocks[0].html.includes('data-align="right"'));
assert.equal((parsed.blocks[0].html.match(/<td /g)||[]).length,4);
assert.ok(parsed.blocks[0].html.includes('a|b'));
console.log('PASS: table alignment, escaped/code pipes, row/header/column boundaries, insertion, deletion, movement, conversions and selection wrapping.');
